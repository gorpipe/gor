package org.gorpipe.compat.gen;

import org.gorpipe.compat.CaseLoader;
import org.gorpipe.compat.CaseStability;
import org.gorpipe.compat.CompatCase;
import org.gorpipe.compat.SurfaceInventory;

import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.stream.Collectors;
import java.util.stream.Stream;

/**
 * Regenerates the baseline case corpus from the registry and the documentation.
 *
 * Writes only case files and the gap report. Baseline outputs are the business of
 * :compat:accept, so that a regeneration never silently rewrites a recorded
 * behaviour.
 */
public final class GenerateMain {

    private GenerateMain() {
    }

    /** The intended on-disk case files, keyed by path. Does not write anything. */
    public static Map<Path, List<CompatCase>> generateAll() {
        SurfaceInventory inventory = SurfaceInventory.read();
        FlagValues values = FlagValues.load();

        List<CompatCase> generated = new ArrayList<>(
                FlagMatrixGenerator.generate(inventory, values).cases);
        generated.addAll(FunctionMatrixGenerator.generate(inventory).cases);
        generated.addAll(DocHarvester.harvest().cases);

        // Nightly only: these are noisier and far more expensive than the flag
        // matrix, and they must not change what the pull-request lane runs.
        if (Boolean.getBoolean("compat.nightly")) {
            generated.addAll(MutationGenerator.mutate(
                    new ArrayList<>(generated), inventory, 500));
            generated.addAll(GrammarFuzzer.generate(inventory, 250));
        }

        Set<String> excluded = readUnreproducible();
        Map<Path, List<CompatCase>> byFile = new TreeMap<>();
        Path caseRoot = CaseLoader.moduleRoot().resolve("cases/baseline");
        for (CompatCase c : generated) {
            if (excluded.contains(c.id)) {
                continue;
            }
            Path file = caseRoot.resolve(c.category()).resolve(c.feature() + ".yml");
            byFile.computeIfAbsent(file, k -> new ArrayList<>()).add(c);
        }
        return byFile;
    }

    /**
     * Ids recorded in inventory/unreproducible.txt.
     *
     * Read as data rather than recomputed, so generateAll() stays pure and fast:
     * the corpus freshness gate calls it on every test run and must not have to
     * execute 500 queries to answer whether the corpus is current.
     */
    private static Set<String> readUnreproducible() {
        Path file = CaseLoader.moduleRoot().resolve("inventory/unreproducible.txt");
        Set<String> ids = new java.util.TreeSet<>();
        if (!Files.exists(file)) {
            return ids;
        }
        try {
            for (String line : Files.readAllLines(file, StandardCharsets.UTF_8)) {
                String trimmed = line.trim();
                if (!trimmed.isEmpty() && !trimmed.startsWith("#")) {
                    ids.add(trimmed);
                }
            }
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot read " + file, e);
        }
        return ids;
    }

    /**
     * Runs every candidate under two roots of different path length and records the
     * ones whose output differs.
     *
     * Recomputed on each generate rather than accumulated, so a case that becomes
     * reproducible again returns to the corpus on its own.
     */
    private static List<String> screenForReproducibility(List<CompatCase> candidates) {
        List<String> unstable = new ArrayList<>();
        for (CompatCase c : candidates) {
            if (!CaseStability.isReproducible(c)) {
                unstable.add(c.id);
            }
        }
        Path file = CaseLoader.moduleRoot().resolve("inventory/unreproducible.txt");
        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by :compat:generate. Cases whose output changed when the "
                + "project\n# root path changed, so no committed baseline could ever match "
                + "them.\n#\n# PIPESTEPS, for one, reports the length of a path. "
                + "Canonicalising ${ROOT} cannot\n# help: the leak is a length, not the "
                + "path. Each line is also a finding about\n# the engine, not merely a "
                + "case to skip.\n");
        for (String id : unstable) {
            sb.append(id).append('\n');
        }
        try {
            Files.createDirectories(file.getParent());
            Files.writeString(file, sb.toString(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot write " + file, e);
        }
        return unstable;
    }

    public static void main(String[] args) {
        SurfaceInventory inventory = SurfaceInventory.read();
        FlagValues values = FlagValues.load();
        FlagMatrixGenerator.GenerationResult flags =
                FlagMatrixGenerator.generate(inventory, values);
        FunctionMatrixGenerator.GenerationResult functions =
                FunctionMatrixGenerator.generate(inventory);
        DocHarvester.HarvestResult docs = DocHarvester.harvest();

        List<CompatCase> candidates = new ArrayList<>(flags.cases);
        candidates.addAll(functions.cases);
        candidates.addAll(docs.cases);
        List<String> unreproducible = screenForReproducibility(candidates);

        Map<Path, List<CompatCase>> byFile = generateAll();
        for (Map.Entry<Path, List<CompatCase>> e : byFile.entrySet()) {
            CaseWriter.writeFeatureFile(e.getKey(), e.getValue());
        }
        int pruned = pruneStaleCaseFiles(byFile.keySet());

        writeGapReport(flags, functions, docs, DocFlagCrossCheck.run(inventory),
                unreproducible);

        System.out.printf("Generated %d baseline cases across %d files (%d stale file(s) "
                + "removed).%n",
                byFile.values().stream().mapToInt(List::size).sum(), byFile.size(), pruned);
        System.out.printf("  flag matrix:  %d cases, %d value-flags unmapped%n",
                flags.cases.size(), flags.unmappedValueFlags.size());
        System.out.printf("  functions:    %d cases, %d not callable from signatures, "
                        + "%d non-deterministic%n",
                functions.cases.size(), functions.unsupported.size(),
                functions.nonDeterministic.size());
        System.out.printf("  doc harvest:  %d cases, %d snippets skipped%n",
                docs.cases.size(), docs.skipped.size());
        System.out.printf("  dropped:      %d case(s) whose output is not reproducible%n",
                unreproducible.size());
        System.out.println("Next: ./gradlew :compat:accept to record baselines for new cases.");
    }

    /**
     * Deletes generated case files the generators no longer produce.
     *
     * Without this a case that stops being generated — a flag that was removed, a
     * doc snippet that became non-deterministic — would linger on disk forever and
     * the freshness gate could never pass again. Confined to cases/baseline, which
     * is generator-owned in its entirety.
     */
    private static int pruneStaleCaseFiles(Set<Path> intended) {
        Path root = CaseLoader.moduleRoot().resolve("cases/baseline");
        if (!Files.isDirectory(root)) {
            return 0;
        }
        int removed = 0;
        try (Stream<Path> walk = Files.walk(root)) {
            List<Path> stale = walk
                    .filter(p -> p.toString().endsWith(".yml"))
                    .filter(p -> !intended.contains(p))
                    .sorted()
                    .collect(Collectors.toList());
            for (Path file : stale) {
                Files.delete(file);
                removed++;
            }
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot prune stale case files under " + root, e);
        }
        return removed;
    }

    private static void writeGapReport(FlagMatrixGenerator.GenerationResult flags,
                                       FunctionMatrixGenerator.GenerationResult functions,
                                       DocHarvester.HarvestResult docs,
                                       DocFlagCrossCheck.CrossCheckResult crossCheck,
                                       List<String> unreproducible) {
        StringBuilder sb = new StringBuilder();
        sb.append("# Generated by :compat:generate. Each line is surface with no case.\n\n");

        sb.append("## Value-taking flags with no entry in inventory/flag-values.yml (")
          .append(flags.unmappedValueFlags.size()).append(")\n");
        for (String entry : flags.unmappedValueFlags) {
            sb.append(entry).append('\n');
        }

        sb.append("\n## Functions with no callable signature (")
          .append(functions.unsupported.size()).append(")\n");
        sb.append("# No sample value exists for one of the argument types, so no "
                + "call was built.\n");
        for (String entry : functions.unsupported) {
            sb.append(entry).append('\n');
        }

        sb.append("\n## Functions screened out as non-deterministic (")
          .append(functions.nonDeterministic.size()).append(")\n");
        sb.append("# Report JVM state, the clock, or the machine, so no stable "
                + "baseline exists.\n");
        for (String entry : functions.nonDeterministic) {
            sb.append(entry).append('\n');
        }

        sb.append("\n## Documentation snippets skipped (")
          .append(docs.skipped.size()).append(")\n");
        for (String entry : docs.skipped) {
            sb.append(entry).append('\n');
        }

        // Recorded here rather than left as a count in the report, so the findings
        // are a reviewable worklist that shows up in the diff when it changes.
        sb.append("\n## Cases dropped as not reproducible (")
          .append(unreproducible.size()).append(")\n");
        sb.append("# Output changed when the project root path changed, so no "
                + "committed baseline\n# could ever match. Recorded in "
                + "inventory/unreproducible.txt.\n");
        for (String entry : unreproducible) {
            sb.append(entry).append('\n');
        }

        sb.append("\n## Phantom flags: documented but NOT registered (")
          .append(crossCheck.phantom.size()).append(")\n");
        sb.append("# Each is either a stale documentation page or a flag that was "
                + "dropped.\n# The second is a real compatibility defect.\n");
        for (String entry : crossCheck.phantom) {
            sb.append(entry).append('\n');
        }

        sb.append("\n## Undocumented flags: registered but absent from the page (")
          .append(crossCheck.undocumented.size()).append(")\n");
        for (String entry : crossCheck.undocumented) {
            sb.append(entry).append('\n');
        }

        Path out = CaseLoader.moduleRoot().resolve("inventory/gaps.txt");
        try {
            Files.createDirectories(out.getParent());
            Files.writeString(out, sb.toString(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException("Cannot write " + out, e);
        }
    }
}
